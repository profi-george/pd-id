// Раньше первое сохранение шло через блокирующий window.confirm() —
// в некоторых браузерах/веб-вью нативный диалог не отрабатывает штатно
// (клик выглядит так, будто "Итог дня" вообще не сохраняется), и это был
// единственный такой диалог во всём приложении (см. requestDelete в
// PriorityMatrix.tsx, где по той же причине отказались от confirm() в
// пользу мягкого "Отменить"). Итог дня и так можно поправить и пересохранить
// в любой момент — отдельное подтверждение здесь не несёт защитной ценности,
// только риск.
export default function EveningSubmitButton({ firstSave }: { firstSave: boolean }) {
  return (
    // Прижата к низу области прокрутки: форма длинная, и «сохранить» не должно
    // теряться где-то ниже сгиба — это единственное завершающее действие экрана.
    <div className="sticky bottom-4 z-10">
      <button type="submit" className="btn btn-primary btn-lg w-full shadow-lg">
        {firstSave ? "Сохранить итог и перенести незавершённое дальше" : "Сохранить изменения"}
      </button>
    </div>
  );
}
